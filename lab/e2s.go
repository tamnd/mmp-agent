func not(b bool, s string) string {
	if b {
		return s
	}
	return "not " + s
}

func describe(g SGerm) string {
	ms := append([][]int(nil), g.Minimizers...)
	sort.Slice(ms, func(i, j int) bool { return less(ms[i], ms[j]) })
	return fmt.Sprintf("mld %d/%d at %v, germ mld %d/%d, %s, %s, divisors %d (%d over the point), %s, %s, group %v",
		g.MldNum, g.MldDen, ms, g.GermMldNum, g.GermMldDen, not(g.Canon, "canonical"), not(g.Terminal, "terminal"),
		g.AtMost1, g.AtMost1Point, not(g.Enc, "enc"), not(g.EncHL, "enc_hl"), g.Group)
}

// RunE2Simplicial enumerates the simplicial toric 3-fold germs of index 2 to MaxIndex and checks the predictions: each terminal germ is cyclic of type 1/r(1, -1, a) with the mld 1 + 1/r (White-Frumkin, Morrison-Stevens), and the cyclic isolated germs agree with the family cyclic.
func RunE2Simplicial(in E2Inputs) (SResult, error) {
	if err := in.check(); err != nil {
		return SResult{}, err
	}
	if in.Dimension != 3 {
		return SResult{}, fmt.Errorf("E2: RunE2Simplicial runs the family simplicial in dimension 3; use RunE2Simplicial4")
	}
	res := SResult{MaxIndex: in.MaxIndex, ListIndex: in.listIndex(), Germs: []SGerm{}, TermFails: []SGerm{}, LemmaFails: []SGerm{}, NoTerminal: []int{}, CompareFails: []string{}}
	type out struct {
		row    SIndex
		germs  []SGerm // the listed germs, or the cyclic isolated germs up to the compare index
		term   []SGerm
		lemma  []SGerm
		isoNC  int
		values map[[2]int]bool
		enc    map[[2]int]bool
	}
	outs := make([]out, in.MaxIndex+1)
	jobs := make(chan int)
	var wg sync.WaitGroup
	for range runtime.NumCPU() {
		wg.Go(func() {
			for r := range jobs {
				o := out{row: SIndex{Index: r}, values: map[[2]int]bool{}, enc: map[[2]int]bool{}}
				simplicialIndex(r, func(g SGerm) {
					o.row.Germs++
					if g.Cyclic {
						o.row.Cyclic++
					}
					if g.Isolated {
						o.row.Isolated++
						if !g.Cyclic {
							o.isoNC++
						}
					}
					if g.Terminal {
						o.row.Terminal++
						w := g.Weights
						ok := g.Cyclic && g.Isolated && g.Lemma != nil && *g.Lemma && g.MldNum == r+1 && g.MldDen == r && g.GermMldNum == r+1 && g.GermMldDen == r
						// The type 1/r(1, -1, a) with gcd(a, r) = 1: each weight is a unit, and two weights add to 0, which is the lemma. Dividing by one of those two weights gives 1 and -1.
						ok = ok && gcd(w[0], r) == 1 && gcd(w[1], r) == 1 && gcd(w[2], r) == 1
						if !ok {
							o.term = append(o.term, g)
						}
					}
					if g.Canon {
						o.row.Canonical++
					}
					if g.Enc {
						o.row.Enc++
					}
					if g.EncHL {
						o.row.EncHL++
						o.enc[[2]int{g.GermMldNum, g.GermMldDen}] = true
					}
					if g.Lemma != nil && *g.Lemma != g.Terminal {
						o.lemma = append(o.lemma, g)
					}
					if g.MldNum < g.MldDen {
						o.values[[2]int{g.MldNum, g.MldDen}] = true
					}
					if r <= res.ListIndex || r <= e2CompareIndex && g.Cyclic && g.Isolated {
						o.germs = append(o.germs, g)
					}
				})
				outs[r] = o
			}
		})
	}
	for r := in.MaxIndex; r >= 2; r-- { // the large indices first, for the balance of the work
		jobs <- r
	}
	close(jobs)
	wg.Wait()
	values, enc := map[[2]int]bool{}, map[[2]int]bool{}
	var cyc []SGerm
	for r := 2; r <= in.MaxIndex; r++ {
		o := outs[r]
		res.Indices = append(res.Indices, o.row)
		t := &res.Total
		t.Germs += o.row.Germs
		t.Cyclic += o.row.Cyclic
		t.Isolated += o.row.Isolated
		t.Terminal += o.row.Terminal
		t.Canonical += o.row.Canonical
		t.Enc += o.row.Enc
		t.EncHL += o.row.EncHL
		res.TermFails = append(res.TermFails, o.term...)
		res.LemmaFails = append(res.LemmaFails, o.lemma...)
		res.IsolatedNotCy += o.isoNC
		if o.row.Terminal == 0 {
			res.NoTerminal = append(res.NoTerminal, r)
		}
		for v := range o.values {
			values[v] = true
		}
		for v := range o.enc {
			enc[v] = true
		}
		for _, g := range o.germs {
			if r <= res.ListIndex {
				res.Germs = append(res.Germs, g)
			}
			if r <= e2CompareIndex && g.Cyclic && g.Isolated {
				cyc = append(cyc, g)
			}
		}
	}
	res.Values, res.EncValues = sortValues(values), sortValues(enc)
	res.compare(cyc, min(in.MaxIndex, e2CompareIndex))
	res.hand()
	return res, nil
}

// compare checks the cyclic isolated germs against the family cyclic, germ for germ.
func (r *SResult) compare(cyc []SGerm, upto int) {
	r.CompareIndex = upto
	old, err := RunE2(E2Inputs{Dimension: 3, MaxIndex: upto})
	if err != nil {
		r.CompareFails = append(r.CompareFails, err.Error())
		return
	}
	byKey := map[string]SGerm{}
	for _, g := range cyc {
		k := fmt.Sprintf("1/%d%v", g.Index, g.Weights)
		if _, ok := byKey[k]; ok {
			r.CompareFails = append(r.CompareFails, k+" twice in the family simplicial")
		}
		byKey[k] = g
	}
	r.CompareGerms = len(old.Germs)
	if len(cyc) != len(old.Germs) {
		r.CompareFails = append(r.CompareFails, fmt.Sprintf("%d cyclic isolated germs, but the family cyclic has %d", len(cyc), len(old.Germs)))
	}
	for _, o := range old.Germs {
		k := fmt.Sprintf("1/%d%v", o.Index, o.Weights)
		g, ok := byKey[k]
		if !ok {
			r.CompareFails = append(r.CompareFails, k+" is not in the family simplicial")
			continue
		}
		// The germ of the enumeration is the group of the weights after a permutation p of the coordinates. Its minimizers must include the point of the smallest k of minimal age of the family cyclic, permuted by the same p.
		found := false
		for _, p := range [6][3]int{{0, 1, 2}, {0, 2, 1}, {1, 0, 2}, {1, 2, 0}, {2, 0, 1}, {2, 1, 0}} {
			var w [3]int
			for i := range 3 {
				w[p[i]] = o.Weights[i]
			}
			if !g.dual.has(o.Index, w) {
				continue
			}
			want := []int{o.MinAgeK * w[0] % o.Index, o.MinAgeK * w[1] % o.Index, o.MinAgeK * w[2] % o.Index}
			for _, m := range g.Minimizers {
				found = found || fmt.Sprint(m) == fmt.Sprint(want)
			}
		}
		if g.MldNum != o.MldNum || g.MldDen != o.MldDen || g.Terminal != o.Terminal || g.Canon != o.Canon || *g.Lemma != *o.Lemma || g.AtMost1 != o.AtMost1 || !found {
			r.CompareFails = append(r.CompareFails, fmt.Sprintf("%s: the family cyclic gives %+v, the family simplicial %s", k, o, describe(g)))
		}
	}
}

// hand computes the hand cases twice, by closure and in the enumeration.
func (r *SResult) hand() {
	byIndex := map[int][]SGerm{}
	for _, c := range handCases {
		if c.r > r.MaxIndex {
			continue
		}
		if _, ok := byIndex[c.r]; !ok {
			byIndex[c.r] = SimplicialGerms(c.r)
		}
		h := HandCase{Name: c.name, Want: c.want}
		g, err := GermOfGens(c.r, c.gens)
		if err != nil {
			h.Got = err.Error()
			r.Hand = append(r.Hand, h)
			continue
		}
		h.Got = describe(g)
		var gs [][]int
		for _, v := range c.gens {
			gs = append(gs, []int{v[0], v[1], v[2]})
		}
		key, n := CanonKey(c.r, gs), 0
		for _, e := range byIndex[c.r] {
			if CanonKey(c.r, e.Gens) != key {
				continue
			}
			n++
			// The germ of the enumeration has other coordinates, so it is compared with the closure of its own generators.
			var es [][3]int
			for _, v := range e.Gens {
				es = append(es, [3]int{v[0], v[1], v[2]})
			}
			if f, err := GermOfGens(c.r, es); err != nil || describe(f) != describe(e) {
				h.Got += "; the enumeration gives " + describe(e)
			}
		}
		h.Found = n == 1
		r.Hand = append(r.Hand, h)
	}
}

// marshalLines writes a JSON array with one element on each line.
func marshalLines[T any](xs []T) []byte {
	var b bytes.Buffer
	b.WriteString("[\n")
	for i, x := range xs {
		data, err := json.Marshal(x)
		if err != nil {
			panic(err) // the types of this package always marshal
		}
		b.Write(data)
		if i < len(xs)-1 {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteString("]\n")
	return b.Bytes()
}

// e2sResult is the one-line result of a run of the family simplicial.
func e2sResult(r SResult) string {
	switch {
	case r.Mismatches() > 0:
		return fmt.Sprintf("mismatch: %d terminal germs are not cyclic of type 1/r(1, -1, a) with the mld 1 + 1/r, %d germs contradict the terminal lemma, %d isolated germs are not cyclic, %d differences with the family cyclic, and %d hand cases disagree", len(r.TermFails), len(r.LemmaFails), r.IsolatedNotCy, len(r.CompareFails), r.Mismatches()-len(r.TermFails)-len(r.LemmaFails)-r.IsolatedNotCy-len(r.CompareFails))
	case r.Gaps() > 0:
		return fmt.Sprintf("incomplete: %d indices have no terminal germ", r.Gaps())
	}
	return fmt.Sprintf("agrees: in %d simplicial toric 3-fold germs with r <= %d, each terminal germ is cyclic of type 1/r(1, -1, a) with the mld 1 + 1/r, and the cyclic isolated germs with r <= %d are those of the family cyclic", r.Total.Germs, r.MaxIndex, r.CompareIndex)
}

func head(xs []string, n int) string {
	if len(xs) <= n {
		return list(xs)
	}
	return strings.Join(xs[:n], ", ") + fmt.Sprintf(", and %d more", len(xs)-n)
}

func e2sSummary(s *Spec, rec *Record, r SResult) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", rec.ID)
	fmt.Fprintf(&b, "%s\n\n", s.Question)
	fmt.Fprintf(&b, "Result: %s.\n\n", rec.Result)
	b.WriteString("## What the run does\n\n")
	fmt.Fprintf(&b, "The run lists each simplicial toric 3-fold germ with 2 <= r <= %d, once up to isomorphism. Such a germ is the cone spanned by e_1, e_2, e_3 in a lattice N with Z^3 ⊆ N ⊂ Q^3, so it is a finite subgroup G = N/Z^3 of (Q/Z)^3, and r is the order of G, the index of Z^3 in N. It is not the Gorenstein index. The e_i are the primitive generators of the rays exactly when no nonzero element of G is on one coordinate, and two germs are isomorphic exactly when their groups differ by a permutation of the coordinates. The run lists the lattices N by the Hermite normal forms of their duals, which are the sublattices of Z^3 of index r, keeps those with primitive rays, and keeps the smallest normal form of the six permutations of the coordinates.\n\n", r.MaxIndex)
	b.WriteString("An element g of G is written (g_1, g_2, g_3) with 0 <= g_i < r, for g_i / r, and its age is (g_1 + g_2 + g_3) / r. The log discrepancy of the divisor of a primitive vector v of the cone is v_1 + v_2 + v_3. A lattice point of the interior of the cone is g plus an integer vector m >= 0 that is positive at the zero coordinates of g, so the mld at the torus-fixed point is the minimum of 3 and of age(g) + #{i : g_i = 0} over the nonzero g, and the minimizers are the points g + (the zero coordinates of g). The mld of the germ, over all exceptional divisors, also counts the divisors over the curves and is the minimum of 2 and of the ages of the nonzero g. The germ is terminal when each nonzero age is more than 1 and canonical when each is at least 1 (Reid-Tai). For an isolated germ the two mlds agree. For a germ that is not isolated they do not: 1/2(1,1,0), A1 times a line, has the mld 2 at the fixed point and the mld 1 as a germ, and it is canonical, not terminal.\n\n")
	b.WriteString("The divisors of log discrepancy at most 1 are the primitive points g of the box with age(g) <= 1: a point g + m with m != 0 has log discrepancy more than 1. The count enc is the old one of E2: exactly one exceptional divisor of log discrepancy at most 1. Han-Liu, Definition 3.8(1), as the note of MMXCD16PTN reads it, also asks that the mld be less than 1, with the mld over all exceptional divisors. The count enc_hl adds that condition. The two differ on the germs whose one divisor has log discrepancy exactly 1, such as 1/2(1,1,0).\n\n")
	b.WriteString("## The checks\n\n")
	fmt.Fprintf(&b, "- Terminal germs. A terminal simplicial toric 3-fold germ is cyclic of type 1/r(1, -1, a) with gcd(a, r) = 1 (White-Frumkin, Morrison-Stevens; the terminal lemma), and its mld is 1 + 1/r. Of the %d terminal germs, %d are not cyclic, isolated, of this type and of this mld.\n", r.Total.Terminal, len(r.TermFails))
	fmt.Fprintf(&b, "- The terminal lemma on the cyclic isolated germs, both ways: %d disagree.\n", len(r.LemmaFails))
	fmt.Fprintf(&b, "- An isolated germ of dimension 3 has a cyclic group: a group (Z/p)^2 in (Z/p)^3 meets each coordinate plane. %d isolated germs are not cyclic. So no germ with a group that is not cyclic is terminal.\n", r.IsolatedNotCy)
	fmt.Fprintf(&b, "- The family cyclic. The %d cyclic isolated germs with r <= %d are compared with a run of the family cyclic, germ for germ: the weights, the mld, a minimizer, terminal, canonical, the terminal lemma and the count of the divisors of log discrepancy at most 1. %d differ.\n", r.CompareGerms, r.CompareIndex, len(r.CompareFails))
	b.WriteString("\nThe cases by hand, computed by the closure of the generators and found once in the enumeration:\n\n| germ | by hand | the run | found once |\n|---|---|---|---|\n")
	for _, h := range r.Hand {
		got := "the same"
		if h.Got != h.Want {
			got = h.Got
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", h.Name, h.Want, got, yes(h.Found))
	}
	t := r.Total
	b.WriteString("\n## The counts\n\n| r | germs | cyclic | isolated | terminal | canonical | enc | enc_hl |\n|---|---|---|---|---|---|---|---|\n")
	fmt.Fprintf(&b, "| all | %d | %d | %d | %d | %d | %d | %d |\n", t.Germs, t.Cyclic, t.Isolated, t.Terminal, t.Canonical, t.Enc, t.EncHL)
	for _, x := range r.Indices {
		fmt.Fprintf(&b, "| %d | %d | %d | %d | %d | %d | %d | %d |\n", x.Index, x.Germs, x.Cyclic, x.Isolated, x.Terminal, x.Canonical, x.Enc, x.EncHL)
	}
	fmt.Fprintf(&b, "\ngerms.json lists the %d germs with r <= %d, one on each line. indices.json has the counts of each index.\n", len(r.Germs), r.ListIndex)
	fmt.Fprintf(&b, "\n## The values\n\nThe mlds at the fixed point below 1: %d distinct values, the smallest %s.\n\nThe mlds of the germs that are enc_hl: %d distinct values, the smallest %s.\n", len(r.Values), head(r.Values, 20), len(r.EncValues), head(r.EncValues, 20))
	if r.Mismatches() > 0 {
		b.WriteString("\n## The germs that contradict a prediction\n\n")
		fails := append(append([]SGerm(nil), r.TermFails...), r.LemmaFails...)
		for i, g := range fails {
			if i == 50 {
				fmt.Fprintf(&b, "- and %d more\n", len(fails)-50)
				break
			}
			fmt.Fprintf(&b, "- r = %d, gens %v: %s\n", g.Index, g.Gens, describe(g))
		}
		for _, f := range r.CompareFails {
			fmt.Fprintf(&b, "- %s\n", f)
		}
	}
	if s.Notes != "" {
		fmt.Fprintf(&b, "\n## Notes\n\n%s\n", strings.TrimSpace(s.Notes))
	}
	b.WriteString("\n## What the run does not do\n\n")
	b.WriteString("- It is a search, not a proof. Only a certificate that Lean checks makes a theorem (spec 13.4).\n")
	b.WriteString("- It covers the simplicial germs of dimension 3 only, not the germs that are not simplicial and not dimension 4.\n")
	b.WriteString("- It counts the toric divisors. That the toric divisors compute the mld of a toric germ is a theorem of route R3 (spec 13.5), not a part of the run.\n")
	b.WriteString("- It runs in the mmp binary, not in a container with pinned images, and it uses no network and no other tool. The record gives the commit of mmp, so the outputs are reproducible.\n")
	return b.String()
}
