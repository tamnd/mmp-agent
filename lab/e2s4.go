// S4Result is the result of a run of the family simplicial in dimension 4.
type S4Result struct {
	MaxIndex  int
	ListIndex int
	Germs     []SGerm
	Indices   []SIndex4
	Total     SIndex4
	// The comparisons up to CompareIndex: the isolated cyclic germs with the family cyclic of dimension 4, and the germs with a zero coordinate with the family simplicial of dimension 3.
	CompareIndex int
	CyclicGerms  int
	CyclicFails  []string
	LineGerms    int
	LineFails    []string
	NoTerminal   []int // the indices with no terminal germ; 1/r(1, -1, 1, -1) is terminal for each r
	Hand         []HandCase
	// TermOther are the terminal germs that are not cyclic and isolated of type 1/r(a, -a, b, -b). They are data, not mismatches.
	TermOther []SGerm
	GorIndex  map[int]int // the number of germs of each Gorenstein index
	Values    []string
	EncValues []string
}

// Mismatches is the number of outputs that contradict a prediction.
func (r S4Result) Mismatches() int {
	n := len(r.CyclicFails) + len(r.LineFails)
	for _, h := range r.Hand {
		if !h.Found || h.Want != h.Got {
			n++
		}
	}
	return n
}

// Gaps is the number of indices where a predicted germ is missing.
func (r S4Result) Gaps() int { return len(r.NoTerminal) }

// pairType says whether a cyclic isolated germ of dimension 4 is 1/r(a, -a, b, -b).
func pairType(g SGerm) bool {
	w, r := g.Weights, g.Index
	if !g.Cyclic || !g.Isolated || len(w) != 4 {
		return false
	}
	for _, p := range [3][4]int{{0, 1, 2, 3}, {0, 2, 1, 3}, {0, 3, 1, 2}} {
		if (w[p[0]]+w[p[1]])%r == 0 && (w[p[2]]+w[p[3]])%r == 0 {
			return true
		}
	}
	return false
}

// zeroCoord returns a coordinate that is 0 on each generator, or -1.
func zeroCoord(g SGerm) int {
	for i := range 4 {
		z := true
		for _, v := range g.Gens {
			z = z && v[i] == 0
		}
		if z {
			return i
		}
	}
	return -1
}

