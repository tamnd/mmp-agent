	fmt.Fprintf(&b, "- The family cyclic. The %d isolated cyclic germs with r <= %d are compared with a run of the family cyclic in dimension 4, germ for germ: the weights, the mld, a minimizer, terminal, canonical and the divisors of log discrepancy at most 1. %d differ.\n", r.CyclicGerms, r.CompareIndex, len(r.CyclicFails))
