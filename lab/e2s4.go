// The family simplicial of E2 in dimension 4 covers each simplicial toric 4-fold germ, as e2s.go does in dimension 3. The germ has the rays e_1, ..., e_4 in a lattice N with Z^4 ⊆ N ⊂ Q^4, so it is a finite subgroup G = N/Z^4 of (Q/Z)^4 of order r. The e_i are primitive exactly when no nonzero element of G is on one coordinate, and two germs are isomorphic exactly when their groups differ by a permutation of the coordinates.
//
// The run lists the duals L = N^* ⊂ Z^4 of index r by their Hermite normal forms H: upper triangular, with the pivots a_1, ..., a_4 and a_1 a_2 a_3 a_4 = r, and each entry above a pivot in [0, pivot). The ray e_i is primitive exactly when the column i of H has the gcd 1, so a_1 = 1. N is H^{-1} Z^4, so G is generated by the columns of r H^{-1}, the adjugate of H, and each element is once the sum of y_j times the column j with 0 <= y_j < a_j. The germ is kept when H is the smallest of the normal forms of the 24 permutations of the coordinates.

// e2MaxIndexSimplicial4 keeps a run of the family simplicial in dimension 4 inside about 15 min on one machine. The work of one index grows like r^3, so the work of a run grows like r^4: on a laptop with 10 cores and other load, index 12 took 0.03 s, index 100 7.2 s, index 150 47 s and index 200 136 s, so index 300 takes about 12 min.
const e2MaxIndexSimplicial4 = 300

// e2CompareIndex4 is the largest index where a run in dimension 4 compares its germs with the family cyclic and with the family simplicial of dimension 3.
const e2CompareIndex4 = 30

type vec4 = [4]int

// perms4 are the 24 permutations of four coordinates, the identity first.
var perms4 = func() [][4]int {
	var out [][4]int
	for a := range 4 {
		for b := range 4 {
			for c := range 4 {
				d := 6 - a - b - c
				if a != b && a != c && b != c && d != a && d != b && d != c {
					out = append(out, [4]int{a, b, c, d})
				}
			}
		}
	}
	return out
}()

// hnf4 returns the Hermite normal form of the lattice spanned by the rows of m, as hnf3 does.
func hnf4(m [4][4]int) [4][4]int {
	for col := range 4 {
		for {
			p := col
			for i := col; i < 4; i++ {
				if m[i][col] != 0 && (m[p][col] == 0 || abs(m[i][col]) < abs(m[p][col])) {
					p = i
				}
			}
			if m[p][col] == 0 {
				return m // the rows are not a basis; the callers give only bases
			}
			m[col], m[p] = m[p], m[col]
			done := true
			for i := col + 1; i < 4; i++ {
				if q := m[i][col] / m[col][col]; q != 0 {
					for j := range 4 {
						m[i][j] -= q * m[col][j]
					}
				}
				if m[i][col] != 0 {
					done = false
				}
			}
			if done {
				break
			}
		}
		if m[col][col] < 0 {
			for j := range 4 {
				m[col][j] = -m[col][j]
			}
		}
		for i := range col {
			q := m[i][col] / m[col][col]
			if m[i][col]-q*m[col][col] < 0 {
				q--
			}
			for j := range 4 {
				m[i][j] -= q * m[col][j]
			}
		}
	}
	return m
}

// dual4 is the Hermite normal form of the dual lattice of a germ of dimension 4.
type dual4 [4][4]int

// key is the entries on and above the diagonal, row by row, for the order of the normal forms.
func (h dual4) key() [10]int {
	var k [10]int
	n := 0
	for i := range 4 {
		for j := i; j < 4; j++ {
			k[n] = h[i][j]
			n++
		}
	}
	return k
}

// has says whether x/r is in N, that is H x = 0 mod r.
func (h dual4) has(r int, x vec4) bool {
	for i := range 4 {
		s := 0
		for j := i; j < 4; j++ {
			s += h[i][j] * x[j]
		}
		if s%r != 0 {
			return false
		}
	}
	return true
}

// smallest says whether no permutation of the coordinates gives a smaller normal form.
func (h dual4) smallest() bool {
	k := h.key()
	for _, p := range perms4[1:] {
		var q [4][4]int
		for i := range 4 {
			for j := range 4 {
				q[i][j] = h[i][p[j]]
			}
		}
		if hk := dual4(hnf4(q)).key(); less(hk[:], k[:]) {
			return false
		}
	}
	return true
}

// adjColumns returns the columns 2, 3 and 4 of r H^{-1}, mod r. They generate G.
func (h dual4) adjColumns(r int) [3]vec4 {
	var out [3]vec4
	for j := 1; j < 4; j++ {
		var x vec4
		for i := 3; i >= 0; i-- {
			s := 0
			if i == j {
				s = r
			}
			for k := i + 1; k < 4; k++ {
				s -= h[i][k] * x[k]
			}
			x[i] = s / h[i][i] // exact, because r H^{-1} is the adjugate of H
		}
		for i := range 4 {
			x[i] = ((x[i] % r) + r) % r
		}
		out[j-1] = x
	}
	return out
}

// groupOf returns the invariant factors of the group from the orders of its elements: for each prime p and each e >= 1, the number of invariant factors divisible by p^e is log_p of |G[p^e]| / |G[p^(e-1)]|.
func groupOf(r int, elems []vec4) []int {
	orders := make([]int, len(elems))
	for i, x := range elems {
		orders[i] = r / gcd(gcd(gcd(gcd(x[0], x[1]), x[2]), x[3]), r)
	}
	count := func(k int) int { // |G[k]|
		n := 0
		for _, o := range orders {
			if k%o == 0 {
				n++
			}
		}
		return n
	}
	f := []int{1, 1, 1, 1} // the invariant factors, the largest first
	m := r
	for p := 2; p <= m; p++ {
		if m%p != 0 {
			continue
		}
		for m%p == 0 {
			m /= p
		}
		prev, pe := 1, p
		for {
			c := count(pe)
			if c == prev {
				break
			}
			ratio, k := c/prev, 0
			for ratio > 1 {
				ratio /= p
				k++
			}
			for i := range k {
				f[i] *= p
			}
			prev, pe = c, pe*p
		}
	}
	var out []int
	for i := 3; i >= 0; i-- {
		if f[i] > 1 {
			out = append(out, f[i])
		}
	}
	if len(out) == 0 {
		out = []int{1}
	}
	return out
}

// evalGerm4 computes a germ of dimension 4 from the elements of its group, as evalGerm does in dimension 3. The mld at the fixed point is the minimum of 4 and of age(g) + #{i : g_i = 0}, and the mld of the germ the minimum of 2 and of the ages, because e_i + e_j is a divisor of log discrepancy 2 over a surface.
func evalGerm4(r int, elems []vec4, in func(vec4) bool, us []int) SGerm {
	g := SGerm{Index: r, Isolated: true, Minimizers: [][]int{}}
	minFix, minAge, sums := 4*r, 4*r, r
	var gen vec4
	for _, x := range elems {
		if x == (vec4{}) {
			continue
		}
		zeros, s := 0, x[0]+x[1]+x[2]+x[3]
		for _, c := range x {
			if c == 0 {
				zeros++
			}
		}
		if zeros > 0 {
			g.Isolated = false
		}
		sums = gcd(sums, s)
		v := s + zeros*r
		if v < minFix {
			minFix = v
			g.Minimizers = g.Minimizers[:0]
		}
		if v == minFix {
			m := []int{x[0], x[1], x[2], x[3]}
			for i := range m {
				if m[i] == 0 {
					m[i] = r
				}
			}
			g.Minimizers = append(g.Minimizers, m)
		}
		minAge = min(minAge, s)
		if gen == (vec4{}) && gcd(gcd(gcd(gcd(x[0], x[1]), x[2]), x[3]), r) == 1 {
			gen = x // an element of order r
		}
		if s <= r && primitive4(x, in) {
			g.AtMost1++
			if zeros == 0 {
				g.AtMost1Point++
			}
		}
	}
	if minFix == 4*r {
		g.Minimizers = append(g.Minimizers, []int{r, r, r, r})
	}
	d := gcd(minFix, r)
	g.MldNum, g.MldDen = minFix/d, r/d
	germ := min(minAge, 2*r)
	d = gcd(germ, r)
	g.GermMldNum, g.GermMldDen = germ/d, r/d
	g.Terminal, g.Canon = minAge > r, minAge >= r
	g.Enc = g.AtMost1 == 1
	g.EncHL = g.Enc && germ < r
	g.GorIndex = r / sums
	g.Group = groupOf(r, elems)
	g.Cyclic = len(g.Group) == 1
	if g.Cyclic {
		g.Weights = normalForm(gen[:], r, us)
	}
	return g
}

// primitive4 says whether the point x/r of N is primitive.
func primitive4(x vec4, in func(vec4) bool) bool {
	c := gcd(gcd(gcd(x[0], x[1]), x[2]), x[3])
	for p := 2; p <= c; p++ {
		if c%p != 0 {
			continue
		}
		for c%p == 0 {
			c /= p
		}
		if in(vec4{x[0] / p, x[1] / p, x[2] / p, x[3] / p}) {
			return false
		}
	}
	return true
}

// germOfDual4 computes the germ of a normal form of the dual lattice.
func germOfDual4(r int, h dual4, us []int, buf []vec4) SGerm {
	cs := h.adjColumns(r)
	elems := buf[:0]
	for y2 := range h[1][1] {
		for y3 := range h[2][2] {
			for y4 := range h[3][3] {
				var x vec4
				for i := range 4 {
					x[i] = (y2*cs[0][i] + y3*cs[1][i] + y4*cs[2][i]) % r
				}
				elems = append(elems, x)
			}
		}
	}
	g := evalGerm4(r, elems, func(x vec4) bool { return h.has(r, x) }, us)
	for _, v := range cs {
		if v != (vec4{}) {
			g.Gens = append(g.Gens, []int{v[0], v[1], v[2], v[3]})
		}
	}
	return g
}

func closure4(r int, gens []vec4) []vec4 {
	set := map[vec4]bool{{}: true}
	elems := []vec4{{}}
	for i := 0; i < len(elems); i++ {
		for _, v := range gens {
			var y vec4
			for j := range 4 {
				y[j] = ((elems[i][j]+v[j])%r + r) % r
			}
			if !set[y] {
				set[y] = true
				elems = append(elems, y)
			}
		}
	}
	return elems
}

// GermOfGens4 computes the germ of dimension 4 of the group generated by the vectors gens/r, by closure, as GermOfGens does in dimension 3.
func GermOfGens4(r int, gens []vec4) (SGerm, error) {
	elems := closure4(r, gens)
	if len(elems) != r {
		return SGerm{}, fmt.Errorf("E2: the group has the order %d, not %d", len(elems), r)
	}
	set := map[vec4]bool{}
	for _, x := range elems {
		set[x] = true
		if nonzero4(x) == 1 {
			return SGerm{}, fmt.Errorf("E2: the element %v of the group is on one coordinate", x)
		}
	}
	g := evalGerm4(r, elems, func(x vec4) bool { return set[x] }, units(r))
	for _, v := range gens {
		g.Gens = append(g.Gens, []int{v[0], v[1], v[2], v[3]})
	}
	return g, nil
}

func nonzero4(x vec4) int {
	n := 0
	for _, c := range x {
		if c != 0 {
			n++
		}
	}
	return n
}

// vec3 drops the coordinate i of x.
func vec3(x vec4, i int) [3]int {
	var y [3]int
	n := 0
	for j := range 4 {
		if j != i {
			y[n] = x[j]
			n++
		}
	}
	return y
}

// CanonKey4 is the normal form of a group of dimension 4 by its elements, over the 24 permutations. It is slow, for the tests and the checks.
func CanonKey4(r int, gens [][]int) string {
	var gs []vec4
	for _, v := range gens {
		gs = append(gs, vec4{v[0], v[1], v[2], v[3]})
	}
	elems := closure4(r, gs)
	var best string
	for _, p := range perms4 {
		xs := make([]vec4, len(elems))
		for i, x := range elems {
			xs[i] = vec4{x[p[0]], x[p[1]], x[p[2]], x[p[3]]}
		}
		sort.Slice(xs, func(i, j int) bool { return less(xs[i][:], xs[j][:]) })
		if k := fmt.Sprint(r, xs); best == "" || k < best {
			best = k
		}
	}
	return best
}

// simplicialIndex4 calls fn on each germ of dimension 4 of one index.
func simplicialIndex4(r int, fn func(SGerm)) {
	us := units(r)
	buf := make([]vec4, 0, r)
	for a2 := 1; a2 <= r; a2++ {
		if r%a2 != 0 {
			continue
		}
		for a3 := 1; a3 <= r/a2; a3++ {
			if r/a2%a3 != 0 {
				continue
			}
			a4 := r / a2 / a3
			for h12 := range a2 {
				if gcd(h12, a2) != 1 {
					continue
				}
				for h13 := range a3 {
					for h23 := range a3 {
						if gcd(gcd(h13, h23), a3) != 1 {
							continue
						}
						for h14 := range a4 {
							for h24 := range a4 {
								for h34 := range a4 {
									if gcd(gcd(gcd(h14, h24), h34), a4) != 1 {
										continue
									}
									h := dual4{{1, h12, h13, h14}, {0, a2, h23, h24}, {0, 0, a3, h34}, {0, 0, 0, a4}}
									if !h.smallest() {
										continue
									}
									fn(germOfDual4(r, h, us, buf))
								}
							}
						}
					}
				}
			}
		}
	}
}

// SimplicialGerms4 returns the germs of dimension 4 of one index.
func SimplicialGerms4(r int) []SGerm {
	var out []SGerm
	simplicialIndex4(r, func(g SGerm) { out = append(out, g) })
	return out
}

