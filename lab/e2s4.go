// RunE2Simplicial4 enumerates the simplicial toric 4-fold germs of index 2 to MaxIndex. It checks that the isolated cyclic germs are those of the family cyclic, that the germs with a zero coordinate are the germs of the family simplicial of dimension 3 times a line, and the hand cases.
func RunE2Simplicial4(in E2Inputs) (S4Result, error) {
	if err := in.check(); err != nil {
		return S4Result{}, err
	}
	if !in.Simplicial() || in.Dimension != 4 {
		return S4Result{}, fmt.Errorf("E2: RunE2Simplicial4 runs the family simplicial in dimension 4")
	}
	res := S4Result{MaxIndex: in.MaxIndex, ListIndex: in.listIndex(), Germs: []SGerm{}, CyclicFails: []string{}, LineFails: []string{}, NoTerminal: []int{}, TermOther: []SGerm{}, GorIndex: map[int]int{}}
	res.CompareIndex = min(in.MaxIndex, e2CompareIndex4)
	type out struct {
		row       SIndex4
		germs     []SGerm // the listed germs
		cyc       []SGerm // the isolated cyclic germs up to the compare index
		lineN     int
		lineFails []string
		other     []SGerm
		gor       map[int]int
		values    map[[2]int]bool
		enc       map[[2]int]bool
	}
	outs := make([]out, in.MaxIndex+1)
	jobs := make(chan int)
	var wg sync.WaitGroup
	for range runtime.NumCPU() {
		wg.Go(func() {
			for r := range jobs {
				o := out{row: SIndex4{Index: r}, gor: map[int]int{}, values: map[[2]int]bool{}, enc: map[[2]int]bool{}}
				compare := r <= res.CompareIndex
				var three map[string]SGerm
				found := map[string]int{}
				if compare {
					three = map[string]SGerm{}
					for _, g := range SimplicialGerms(r) {
						three[CanonKey(r, g.Gens)] = g
					}
				}
				simplicialIndex4(r, func(g SGerm) {
					o.row.Germs++
					o.gor[g.GorIndex]++
					if g.Cyclic {
						o.row.Cyclic++
					}
					if g.Isolated {
						o.row.Isolated++
					}
					if g.Terminal {
						o.row.Terminal++
						if !pairType(g) {
							o.other = append(o.other, g)
						}
					}
					if g.Canon {
						o.row.Canonical++
					}
					if g.GorIndex == 1 {
						o.row.Gorenstein++
					}
					if g.Enc {
						o.row.Enc++
					}
					if g.EncHL {
						o.row.EncHL++
						o.enc[[2]int{g.GermMldNum, g.GermMldDen}] = true
					}
					if g.MldNum < g.MldDen {
						o.values[[2]int{g.MldNum, g.MldDen}] = true
					}
					z := zeroCoord(g)
					if z >= 0 {
						o.row.Line++
					}
					if compare && z >= 0 {
						o.lineN++
						var gs [][]int
						for _, v := range g.Gens {
							y := vec3(vec4{v[0], v[1], v[2], v[3]}, z)
							if y != [3]int{} {
								gs = append(gs, y[:])
							}
						}
						k := CanonKey(r, gs)
						t, ok := three[k]
						found[k]++
						switch {
						case !ok:
							o.lineFails = append(o.lineFails, fmt.Sprintf("r = %d, gens %v: the 3-fold germ is not in the family simplicial of dimension 3", r, g.Gens))
						case g.MldNum*t.MldDen != (t.MldNum+t.MldDen)*g.MldDen || g.GermMldNum != t.GermMldNum || g.GermMldDen != t.GermMldDen || g.Terminal != t.Terminal || g.Canon != t.Canon || g.AtMost1 != t.AtMost1 || g.AtMost1Point != 0 || fmt.Sprint(g.Group) != fmt.Sprint(t.Group):
							o.lineFails = append(o.lineFails, fmt.Sprintf("r = %d, gens %v: %s, but the 3-fold germ times a line has %s", r, g.Gens, describe(g), describe(t)))
						}
					}
					if compare && g.Cyclic && g.Isolated {
						o.cyc = append(o.cyc, g)
					}
					if r <= res.ListIndex {
						o.germs = append(o.germs, g)
					}
				})
				if compare {
					for k, t := range three {
						if found[k] != 1 {
							o.lineFails = append(o.lineFails, fmt.Sprintf("r = %d: the 3-fold germ %v times a line is found %d times", r, t.Gens, found[k]))
						}
					}
					sort.Strings(o.lineFails)
				}
				outs[r] = o
			}
		})
	}
	for r := in.MaxIndex; r >= 2; r-- {
		jobs <- r
	}
	close(jobs)
	wg.Wait()
	values, enc := map[[2]int]bool{}, map[[2]int]bool{}
	var cyc []SGerm
	for r := 2; r <= in.MaxIndex; r++ {
		o := outs[r]
		res.Indices = append(res.Indices, o.row)
		res.Total.add(o.row)
		res.Germs = append(res.Germs, o.germs...)
		res.LineGerms += o.lineN
		res.LineFails = append(res.LineFails, o.lineFails...)
		res.TermOther = append(res.TermOther, o.other...)
		cyc = append(cyc, o.cyc...)
		if o.row.Terminal == 0 {
			res.NoTerminal = append(res.NoTerminal, r)
		}
		for k, n := range o.gor {
			res.GorIndex[k] += n
		}
		for v := range o.values {
			values[v] = true
		}
		for v := range o.enc {
			enc[v] = true
		}
	}
	res.Values, res.EncValues = sortValues(values), sortValues(enc)
	res.compareCyclic(cyc)
	res.hand()
	return res, nil
}

// compareCyclic checks the isolated cyclic germs against the family cyclic of dimension 4, germ for germ.
func (r *S4Result) compareCyclic(cyc []SGerm) {
	old, err := RunE2(E2Inputs{Dimension: 4, MaxIndex: r.CompareIndex})
	if err != nil {
		r.CyclicFails = append(r.CyclicFails, err.Error())
		return
	}
	byKey := map[string]SGerm{}
	for _, g := range cyc {
		k := fmt.Sprintf("1/%d%v", g.Index, g.Weights)
		if _, ok := byKey[k]; ok {
			r.CyclicFails = append(r.CyclicFails, k+" twice in the family simplicial")
		}
		byKey[k] = g
	}
	r.CyclicGerms = len(old.Germs)
	if len(cyc) != len(old.Germs) {
		r.CyclicFails = append(r.CyclicFails, fmt.Sprintf("%d isolated cyclic germs, but the family cyclic has %d", len(cyc), len(old.Germs)))
	}
	for _, o := range old.Germs {
		k := fmt.Sprintf("1/%d%v", o.Index, o.Weights)
		g, ok := byKey[k]
		if !ok {
			r.CyclicFails = append(r.CyclicFails, k+" is not in the family simplicial")
			continue
		}
		// A minimizer of the family cyclic, k (a_1, ..., a_4) for its smallest k of minimal age, after the permutation that puts the weights in the coordinates of the germ.
		found := false
		for _, p := range perms4 {
			var w vec4
			for i := range 4 {
				w[p[i]] = o.Weights[i]
			}
			if !closureHas(o.Index, g.Gens, w) {
				continue
			}
			want := fmt.Sprint([]int{o.MinAgeK * w[0] % o.Index, o.MinAgeK * w[1] % o.Index, o.MinAgeK * w[2] % o.Index, o.MinAgeK * w[3] % o.Index})
			for _, m := range g.Minimizers {
				found = found || fmt.Sprint(m) == want
			}
		}
		if g.MldNum != o.MldNum || g.MldDen != o.MldDen || g.Terminal != o.Terminal || g.Canon != o.Canon || g.AtMost1 != o.AtMost1 || !found {
			r.CyclicFails = append(r.CyclicFails, fmt.Sprintf("%s: the family cyclic gives %+v, the family simplicial %s", k, o, describe(g)))
		}
	}
}

// closureHas says whether w/r is in the group generated by gens/r.
func closureHas(r int, gens [][]int, w vec4) bool {
	var gs []vec4
	for _, v := range gens {
		gs = append(gs, vec4{v[0], v[1], v[2], v[3]})
	}
	for _, x := range closure4(r, gs) {
		if x == w {
			return true
		}
	}
	return false
}

// hand computes the hand cases twice, by closure and in the enumeration.
func (r *S4Result) hand() {
	byIndex := map[int][]SGerm{}
	for _, c := range handCases4 {
		if c.r > r.MaxIndex {
			continue
		}
		if _, ok := byIndex[c.r]; !ok {
			byIndex[c.r] = SimplicialGerms4(c.r)
		}
		h := HandCase{Name: c.name, Want: c.want}
		g, err := GermOfGens4(c.r, c.gens)
		if err != nil {
			h.Got = err.Error()
			r.Hand = append(r.Hand, h)
			continue
		}
		h.Got = describe(g)
		var gs [][]int
		for _, v := range c.gens {
			gs = append(gs, []int{v[0], v[1], v[2], v[3]})
		}
		key, n := CanonKey4(c.r, gs), 0
		for _, e := range byIndex[c.r] {
			if CanonKey4(c.r, e.Gens) != key {
				continue
			}
			n++
			var es []vec4
			for _, v := range e.Gens {
				es = append(es, vec4{v[0], v[1], v[2], v[3]})
			}
			if f, err := GermOfGens4(c.r, es); err != nil || describe(f) != describe(e) {
				h.Got += "; the enumeration gives " + describe(e)
			}
		}
		h.Found = n == 1
		r.Hand = append(r.Hand, h)
	}
}

// e2s4Result is the one-line result of a run of the family simplicial in dimension 4.
func e2s4Result(r S4Result) string {
	switch {
	case r.Mismatches() > 0:
		return fmt.Sprintf("mismatch: %d differences with the family cyclic, %d differences with the 3-fold germs times a line, and %d hand cases disagree", len(r.CyclicFails), len(r.LineFails), r.Mismatches()-len(r.CyclicFails)-len(r.LineFails))
	case r.Gaps() > 0:
		return fmt.Sprintf("incomplete: %d indices have no terminal germ", r.Gaps())
	}
	return fmt.Sprintf("agrees: in %d simplicial toric 4-fold germs with r <= %d, the isolated cyclic germs with r <= %d are those of the family cyclic, the germs with a zero coordinate are the 3-fold germs of the family simplicial times a line, and each index has a terminal germ", r.Total.Germs, r.MaxIndex, r.CompareIndex)
}

