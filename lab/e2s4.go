	b.WriteString("## What the run does\n\n")
	fmt.Fprintf(&b, "The run lists each simplicial toric 4-fold germ with 2 <= r <= %d, once up to isomorphism, as the family simplicial does in dimension 3. The germ is the cone spanned by e_1, ..., e_4 in a lattice N with Z^4 ⊆ N ⊂ Q^4, so it is a finite subgroup G = N/Z^4 of (Q/Z)^4, and r is the order of G. It is not the Gorenstein index, which is the column gorenstein_index of germs.json. The e_i are primitive exactly when no nonzero element of G is on one coordinate, and two germs are isomorphic exactly when their groups differ by a permutation of the coordinates. The run lists the Hermite normal forms of the duals, the sublattices of Z^4 of index r, keeps those with primitive rays, and keeps the smallest normal form of the 24 permutations of the coordinates.\n\n", r.MaxIndex)
	b.WriteString("An element g of G is written (g_1, ..., g_4) with 0 <= g_i < r, for g_i / r, and its age is (g_1 + ... + g_4) / r. The mld at the torus-fixed point is the minimum of 4 and of age(g) + #{i : g_i = 0} over the nonzero g, with the minimizers g + (the zero coordinates of g). The mld of the germ, over all exceptional divisors, is the minimum of 2 and of the ages: e_i + e_j is a divisor of log discrepancy 2. Terminal and canonical are the ages more than 1 and at least 1 (Reid-Tai). The divisors of log discrepancy at most 1 are the primitive box points of age at most 1; enc and enc_hl are as in dimension 3. A germ is Gorenstein when each age is an integer.\n\n")
